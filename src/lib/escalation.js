// Правила поверх ответа модели (и заглушки): звать ли менеджера и какие поля поправить.
// Решает код, по тексту заявки и полям ответа. Самооценке модели здесь не верят:
// на живом прогоне 2026-10-05 confidence был 0,90–0,99 во всех 42 ответах, у ошибок тоже,
// и правило «ниже 0,6 — к человеку» не сработало ни разу. confidence остаётся в ответе
// как данные, на маршрут не влияет. Флаг модели needs_human — один из поводов: он может
// добавить человека, но не убрать. Текст — замаскированный, как его видела модель.
// Регулярные выражения с флагом u: \b в JS не видит кириллицу, границы слов — (?<!\p{L}) и (?!\p{L}).

// Слова, из которых не складывается просьба: приветствие, вежливость, «у меня вопрос»,
// «перезвоните», контакты. Заявка только из них — «нет сути». Буква ё заменена на е.
const ESC_FILLER = new Set((
  'здравствуйте здраствуйте здравствуй здрасьте здрасте привет приветик приветствую '
  + 'добрый доброе доброго добрая день дня утро утра вечер вечера ночи время времени суток '
  + 'hello hi hey good morning afternoon evening '
  + 'спасибо пожалуйста благодарю извините простите '
  + 'алло ау эй есть кто тут здесь кто-нибудь кто-то живой живые '
  + 'у меня мне нас нам я мы вы вас вам ваш ваша с со мной нами по и а но на в к бы же ли не можно могу '
  + 'вопрос вопросик вопросы просьба дело тема поводу такой такое такая один одна '
  + 'подскажите скажите хотел хотела хотели хочу уточнить узнать спросить обратиться обращаюсь пишу написать '
  + 'перезвоните позвоните наберите звоните свяжитесь напишите пишите ответьте жду ждем ответа звонка '
  + 'мой моя мои номер телефон тел почта email e-mail контакты контакт зовут'
).split(' '));

// Признаки просьбы или вопроса. Нет ни одного (и нет услуги, поломки, претензии) — «нет просьбы».
const ESC_REQUEST_RE = /\?|(?<!\p{L})(?:нуж\p{L}*|надо|необходим\p{L}*|требуе?тся|хоч\p{L}*|хотим|хотел\p{L}*|интерес\p{L}*|подскаж\p{L}*|посовету\p{L}*|сколько|скока|почем|можно|прошу|просим|помогите|ищу|ищем|планиру\p{L}*|понадоб\p{L}*|заказ\p{L}*|закаж\p{L}*|предлагаем)(?!\p{L})/iu;
// повелительное наклонение: «почините», «пришлите», «верните» (но не «здравствуйте»)
const ESC_IMPERATIVE_RE = /(?<!\p{L})(?!здравств|здраств)\p{L}{2,}(?:ите|йте)(?!\p{L})/iu;
// инфинитив в начале фразы: «Смонтировать видеонаблюдение в коттедже»
const ESC_INFINITIVE_RE = /(?:^|[.!?;\n]\s*)\p{L}{3,}(?:ть|ти)(?:ся)?(?!\p{L})/iu;

// Упоминания услуги не как просьба: «после ремонта», «по ремонту котла», «взяли у вас
// в прокат», «монтажник», «монтажных компаний». Вырезаются перед подсчётом просьб.
const ESC_CONTEXT_RES = [
  /(?<!\p{L})(?:после|при|по|для|от|во\s+время)\s+(?:\p{L}+\s+)?(?:ремонт|монтаж|установк|аренд|проката|переезд)\p{L}*/iu,
  /(?<!\p{L})(?:взял\p{L}*|брал\p{L}*|арендовал\p{L}*)\s+(?:\p{L}+\s+){0,3}?(?:в|на)\s+(?:аренду|прокат)/iu,
  /(?<!\p{L})монтажн\p{L}*\s+(?:компани|бригад|организаци|фирм|контор)\p{L}*/iu,
  /(?<!\p{L})(?:монтажник|ремонтник)\p{L}*/iu,
];

// Встречное предложение: клиент сам предлагает компании сдать ей в аренду или продать своё.
// Это не заказ услуги, а предложение партнёра; как просьба считается отдельно от аренды.
const ESC_RENT_OUT_RES = [
  /(?<!\p{L})(?:сдать|сдадим|сдаем)[\s,]+(?:\p{L}+[\s,]+){0,3}?(?:вам|вашей\s+компании)[\s,]+(?:\p{L}+[\s,]+){0,2}?в\s+(?:аренду|прокат|субаренду)(?!\p{L})/iu,
  /(?<!\p{L})(?:сдать|сдадим|сдаем)[\s,]+(?:\p{L}+[\s,]+){0,3}?в\s+(?:аренду|прокат|субаренду)\s+(?:вам|вашей\s+компании)(?!\p{L})/iu,
  /(?<!\p{L})(?:продать|продадим|продаем)[\s,]+(?:\p{L}+[\s,]+){0,3}?(?:вам|вашей\s+компании)(?!\p{L})/iu,
];

// Симптом поломки — это просьба о ремонте, даже без слова «ремонт».
const ESC_SYMPTOM_RES = [
  /(?<!\p{L})(?:сломал|перестал|неисправ|поломк)\p{L}*/iu,
  /(?<!\p{L})не\s+(?:работа|заводит|включа|слива|грее|греют|набира|всасыва|крутит|запуска|морозит|охлажда|печата|тянет|кача)\p{L}*/iu,
  /(?<!\p{L})выда[её]т\s+ошибк/iu,
];
// Просьбы по услугам: ремонт (в том числе симптом поломки), аренда, монтаж.
const ESC_INTENTS = [
  ['repair', [
    /(?<!\p{L})(?:отремонтир|почин|подремонт|ремонт|диагностик|техобслуж|обслуживани|замен)\p{L}*/iu,
    /(?<!\p{L})ТО(?!\p{L})/u,
  ].concat(ESC_SYMPTOM_RES)],
  ['rental', [
    /(?<!\p{L})(?:в|на)\s+(?:аренду|прокат|субаренду)(?!\p{L})/iu,
    /(?<!\p{L})(?:напрокат|прокат\p{L}*|аренд(?:а|у|ы|е|ой|овать|уем|ую|ует))(?!\p{L})/iu,
  ]],
  ['installation', [
    /(?<!\p{L})(?:монтаж|смонтир|демонтаж|пусконаладк)\p{L}*/iu,
    /(?<!\p{L})(?:установ(?:ить|ка|ки|ку|кой|ите|им|лю)|подключ(?:ить|ение|ения|ите|им)|повесить)(?!\p{L})/iu,
    /(?<!\p{L})провести\s+(?:свет|проводку|кабель|интернет|электрику)/iu,
  ]],
];
const ESC_INTENT_RU = { repair: 'ремонт', rental: 'аренда', installation: 'монтаж', rent_out: 'сдать или продать компании своё' };

// Предложение поставщика или партнёра: не спам и не заказ, а дело для менеджера.
const ESC_PARTNER_RES = [
  /(?<!\p{L})(?:сотрудничеств|партнерств|дилерств|субподряд)\p{L}*/iu,
  /(?<!\p{L})(?:предлагаем|предложим|готовы\s+(?:поставлять|предложить|продать|поставить)|можем\s+(?:поставлять|предложить|выслать|отправить|прислать|поставить)|вышлем|пришлем)[\s,]+(?:\p{L}+[\s,]+){0,3}?(?:скидк|прайс|каталог|коммерческ|кп(?!\p{L})|поставк|продукци|товар|материал|услуг)\p{L}*/iu,
  /(?<!\p{L})предлагаем\s+(?:\p{L}+\s+){0,2}?(?:вам|вашей\s+компании)(?!\p{L})/iu,
];
// «Мы производитель / дилер / завод» — предложение, только если сами они ничего не заказывают
// («мы — завод, у нас сломался станок» — это клиент).
const ESC_SUPPLIER_SELF_RE = /(?<!\p{L})(?:мы|наша\s+компания|являемся)[\s,—-]+(?:\p{L}+[\s,—-]+){0,2}?(?:производител|поставщик|дистрибьютор|дилер|завод|оптов)\p{L}*/iu;
// Явная реклама: с ней предложение остаётся спамом, менеджер не нужен.
const ESC_HARD_SPAM_RE = /(?<!\p{L})(?:казино|ставк\p{L}*\s+на\s+спорт|крипт\p{L}*|заработ\p{L}*|пассивн\p{L}*\s+доход|без\s+вложений|продвижени\p{L}*|раскрутк\p{L}*|seo|сео|топ-?\d+|подписчик\p{L}*|лайк\p{L}*|рассылк\p{L}*|баз\p{L}*\s+(?:клиентов|контактов|данных)|ссылк\p{L}*\s+в\s+профиле|в\s+лс)(?!\p{L})|https?:|www\./iu;

// Претензия в тексте: категория должна быть complaint.
const ESC_COMPLAINT_RE = /(?<!\p{L})(?:претензи\p{L}*|жалоб\p{L}*|недовол\p{L}*|возмущ\p{L}*|безобрази\p{L}*|обманул\p{L}*|компенсац\p{L}*|требую|верните[\s,]+(?:\p{L}+[\s,]+)?(?:деньги|оплату|средства|предоплату)|возврат\p{L}*\s+(?:денег|средств|оплаты|предоплаты)|хотим\s+возврат)(?!\p{L})/iu;
// Срочно (но не «не срочно») и явно не срочно.
const ESC_URGENT_RE = /(?<!не\s)(?<!\p{L})(?:срочн\p{L}*|немедленн\p{L}*|авари\p{L}*|простаива\p{L}*|сегодня|прямо\s+сейчас|как\s+можно\s+скорее|в\s+течение\s+часа)(?!\p{L})/iu;
const ESC_NOT_URGENT_RE = /(?<!\p{L})(?:не\s+срочно|несрочно|не\s+горит|не\s+к\s+спеху|не\s+спешим|не\s+торопимся|торопиться\s+некуда|когда\s+будет\s+время)(?!\p{L})/iu;
// Срок выполнения дальше недели: с ним срочность low законна.
const ESC_FAR_DEADLINE_RE = /(?<!\p{L})(?:в\s+течени[еи]\s+(?:\p{L}+\s+)?(?:месяц|месяца|недел\p{L}*|квартал\p{L}*|год\p{L}*|полугод\p{L}*)|через\s+(?:\p{N}+\s+|\p{L}+\s+)?(?:месяц\p{L}*|недел\p{L}*|полгода|год\p{L}*|квартал)|в\s+след(?:ующем|\.)?\s*(?:месяц\p{L}*|году|квартал\p{L}*)|на\s+следующей\s+неделе|на\s+будущее|заранее|планиру\p{L}*|в\s+(?:январ|феврал|март|апрел|ма[йе]|июн|июл|август|сентябр|октябр|ноябр|декабр)\p{L}*|к\s+(?:лету|осени|зиме|весне|концу\s+(?:месяца|года|квартала)))(?!\p{L})/iu;
// Длительность аренды или работ: «на месяц», «на неделю», «дня на 3», «от полугода».
// Это не срок выполнения: «аренда на месяц» не значит «через месяц».
const ESC_TERM_RE = /(?<!\p{L})(?:(?:на|от|сроком\s+на)\s+(?:\p{N}+\s*|пару\s+|несколько\s+|один\s+|одну\s+|два\s+|две\s+|три\s+|четыре\s+|пять\s+|шесть\s+)?(?:сутки|суток|день|дня|дней|неделю|недели|недель|месяц|месяца|месяцев|полгода|полугода|год|года|лет|выходные)|(?:дня|дней|недели|недель|месяца|месяцев)\s+на\s+\p{N}+|(?:долгосрочн|посуточн|помесячн)\p{L}*)(?!\p{L})/iu;

// Просьба прислать документы (лицензии, договор, СРО), а не сделать работу.
const ESC_DOC_NOUN = '(?:лиценз\\p{L}*|сертификат\\p{L}*|допуск\\p{L}*|сро(?!\\p{L})|реквизит\\p{L}*|выписк\\p{L}*|устав(?:а|ом)?(?!\\p{L})|документ\\p{L}*|договор\\p{L}*|образ[еч]\\p{L}*|портфолио)';
const ESC_DOC_REQUEST_RE = new RegExp('(?<!\\p{L})(?:нужн\\p{L}*|пришлите|вышлите|скиньте|отправьте|направьте|предостав\\p{L}*|покажите|дайте|запрашива\\p{L}*|прошу|просим|есть\\s+ли(?:\\s+у\\s+вас)?|интересу\\p{L}*)[\\s,]+(?:\\p{L}+[\\s,]+){0,3}?' + ESC_DOC_NOUN, 'iu');
const ESC_DOC_ANY_RE = new RegExp('(?<!\\p{L})' + ESC_DOC_NOUN, 'iu');
const ESC_TENDER_RE = /(?<!\p{L})(?:тендер\p{L}*|закупк\p{L}*|конкурс\p{L}*)/iu;
// Заказ самой работы: «нужен монтаж», «можно заказать ремонт», «почините», «Смонтировать …».
const ESC_WORK_ORDER_RES = [
  /(?<!\p{L})(?:нуж\p{L}*|надо|необходим\p{L}*|требуе?тся|хотим|хочу|хотел\p{L}*|закаж\p{L}*|заказать|понадоб\p{L}*|сделайте|сделать|можно|интересует)[\s,]+(?:\p{L}+[\s,]+){0,2}?(?:монтаж|смонтир|установ|подключ|ремонт|отремонт|почин|аренд|прокат|диагностик|замен|обслуж)\p{L}*/iu,
  /(?<!\p{L})(?:смонтируйте|установите|подключите|почините|отремонтируйте|привезите|повесьте|замените|приезжайте)(?!\p{L})/iu,
  /(?:^|[.!?;\n]\s*)(?:смонтировать|установить|подключить|починить|отремонтировать|арендовать|повесить|заменить)(?!\p{L})/iu,
  /(?<!\p{L})(?:в|на)\s+(?:аренду|прокат)(?!\p{L})/iu,
];

// Вырезает все вхождения: у регулярок выше нет флага g, чтобы .test() не помнил lastIndex.
function escCut(text, re) {
  return text.replace(new RegExp(re.source, re.flags + 'g'), ' ');
}

function escNorm(text) {
  return String(text == null ? '' : text).replace(/ё/g, 'е').replace(/Ё/g, 'Е');
}

// Текст без меток маскирования и вырезанных тегов: «[телефон скрыт]» — не суть заявки.
function escStripLabels(text) {
  return escNorm(text).replace(/\[[^\]\n]{0,40}\]/g, ' ');
}

// Только приветствие, вежливость, «у меня вопрос», «перезвоните», контакты — сути нет.
function escNoSubstance(text) {
  const t = escStripLabels(text).replace(/([Зз]овут)\s+\p{Lu}\p{L}*(?:\s+\p{Lu}\p{L}*)?/gu, '$1');
  const words = t.toLowerCase().match(/[\p{L}\p{N}]+(?:-[\p{L}\p{N}]+)*/gu) || [];
  return words.filter((w) => /\p{L}/u.test(w) && !ESC_FILLER.has(w)).length === 0;
}

// Какие услуги клиент просит (без упоминаний «после ремонта» и т. п.).
function escIntents(text) {
  let t = escStripLabels(text);
  const found = [];
  if (ESC_RENT_OUT_RES.some((re) => re.test(t))) {
    found.push('rent_out');
    for (const re of ESC_RENT_OUT_RES) t = escCut(t, re);
  }
  for (const re of ESC_CONTEXT_RES) t = escCut(t, re);
  for (const [name, res] of ESC_INTENTS) if (res.some((re) => re.test(t))) found.push(name);
  return found;
}

function escHasRequest(text, intents) {
  const t = escStripLabels(text);
  return ESC_REQUEST_RE.test(t) || ESC_IMPERATIVE_RE.test(t) || ESC_INFINITIVE_RE.test(t.trim())
    || intents.length > 0 || ESC_COMPLAINT_RE.test(t);
}

function escPartnerOffer(text) {
  const t = escStripLabels(text);
  if (ESC_HARD_SPAM_RE.test(t)) return false;
  if (ESC_PARTNER_RES.some((re) => re.test(t)) || ESC_RENT_OUT_RES.some((re) => re.test(t))) return true;
  const ownNeed = ESC_WORK_ORDER_RES.some((re) => re.test(t)) || ESC_SYMPTOM_RES.some((re) => re.test(t));
  return !ownNeed && ESC_SUPPLIER_SELF_RE.test(t);
}

// Клиент просит документы, а не работу: «для тендера нужны лицензии и договор на монтаж».
function escDocsNotWork(text) {
  const t = escStripLabels(text);
  const docs = ESC_DOC_REQUEST_RE.test(t) || (ESC_TENDER_RE.test(t) && ESC_DOC_ANY_RE.test(t));
  return docs && !ESC_WORK_ORDER_RES.some((re) => re.test(t)) && !ESC_SYMPTOM_RES.some((re) => re.test(t));
}

// Правила поверх проверенного ответа t (поля как у validateTriage).
// Сначала поправки полей (категория, срочность), потом поводы позвать менеджера.
// modelFlag — как назвать флаг needs_human из ответа («модель отметила …»); null — флаг
// учитывается, но поводом не пишется (у заглушки после двух неудач свой повод в трассе).
// Возвращает исправленный ответ, поводы [{code, text}] и поправки [{code, text}].
function applyEscalationRules(text, t, modelFlag) {
  const fixes = [];
  const reasons = [];
  const raw = escStripLabels(text);
  let category = t.category;
  let urgency = t.urgency;

  if ((category === 'installation' || category === 'repair' || category === 'rental') && escDocsNotWork(raw)) {
    fixes.push({ code: 'category_docs', text: 'category: ' + category + ' → consultation: просят документы, а не работу' });
    category = 'consultation';
  }
  const term = ESC_TERM_RE.exec(raw);
  if (urgency === 'low' && category !== 'spam' && term && !ESC_FAR_DEADLINE_RE.test(raw) && !ESC_NOT_URGENT_RE.test(raw)) {
    fixes.push({ code: 'urgency_term', text: 'urgency: low → normal: «' + term[0] + '» — срок аренды или работ, а не срок выполнения' });
    urgency = 'normal';
  }

  const intents = escIntents(raw);
  if (category === 'complaint') reasons.push({ code: 'complaint', text: 'жалоба' });
  if (escNoSubstance(raw)) {
    reasons.push({ code: 'no_substance', text: 'нет сути: только приветствие или контакты' });
  } else if (category !== 'spam' && !escHasRequest(raw, intents)) {
    reasons.push({ code: 'no_request', text: 'нет просьбы: непонятно, что нужно клиенту' });
  }
  // у жалобы аренда и поломка — обычно контекст претензии, а не две просьбы: повода «жалоба» хватает
  if (intents.length > 1 && category !== 'complaint') {
    reasons.push({ code: 'multiple_requests', text: 'несколько просьб: ' + intents.map((i) => ESC_INTENT_RU[i]).join(' и ') });
  }
  if (escPartnerOffer(raw)) {
    reasons.push({ code: 'partner_offer', text: 'предложение поставщика или партнёра, а не заказ' });
  }
  const conflicts = [];
  if (category === 'spam' && urgency === 'high') conflicts.push('спам со срочностью high');
  const services = intents.filter((i) => i !== 'rent_out');
  if (category === 'spam' && services.length) conflicts.push('спам, а в тексте просьба: ' + services.map((i) => ESC_INTENT_RU[i]).join(', '));
  if (category !== 'complaint' && ESC_COMPLAINT_RE.test(raw)) conflicts.push('в тексте претензия, а category ' + category);
  if (urgency === 'low' && ESC_URGENT_RE.test(raw)) conflicts.push('urgency low, а в тексте «срочно» или «сегодня»');
  if (urgency === 'high' && ESC_NOT_URGENT_RE.test(raw) && !ESC_URGENT_RE.test(raw)) conflicts.push('urgency high, а в тексте «не срочно»');
  if (conflicts.length) reasons.push({ code: 'contradiction', text: 'поля противоречат: ' + conflicts.join('; ') });
  if (t.needs_human === true && modelFlag) reasons.push({ code: 'model_flag', text: modelFlag });

  return {
    triage: { ...t, category, urgency, needs_human: t.needs_human === true || reasons.length > 0 },
    reasons,
    fixes,
  };
}
