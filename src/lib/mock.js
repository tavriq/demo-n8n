const CATEGORY_RU = {
  repair: 'Ремонт', rental: 'Аренда', installation: 'Монтаж', consultation: 'Консультация',
  complaint: 'Жалоба', spam: 'Спам', other: 'Другое',
};

function mockParseBudget(text) {
  const re = /(\d[\d  ]*(?:[.,]\d+)?)\s*(тыс\S*|т\.р\.?|к(?![а-яё])|млн|миллион\S*)?\s*(руб\S*|р\.|₽)?/gi;
  let m;
  while ((m = re.exec(text)) !== null) {
    const numStr = m[1].replace(/[  ]/g, '').replace(',', '.');
    const mult = (m[2] || '').toLowerCase();
    const cur = m[3];
    const before = text.slice(Math.max(0, m.index - 25), m.index).toLowerCase();
    if (!mult && !cur && !/бюджет/.test(before)) continue;
    let value = parseFloat(numStr);
    if (!isFinite(value)) continue;
    if (mult.startsWith('тыс') || mult.startsWith('т.р') || mult === 'к') value *= 1000;
    if (mult.startsWith('млн') || mult.startsWith('миллион')) value *= 1000000;
    if (value <= 0) continue;
    return Math.round(value);
  }
  return null;
}

function mockTriage(text) {
  const t = String(text || '');
  let best = 'other';
  let bestHits = 0;
  for (const [cat, patterns] of MOCK_RULES) {
    const hits = patterns.filter((re) => re.test(t)).length;
    if (hits > bestHits) { best = cat; bestHits = hits; }
  }
  let urgency = 'normal';
  if (/(не срочно|несрочно|когда будет время|в течение месяца|на следующей неделе|в следующем месяце|планируем|заранее)/i.test(t)) urgency = 'low';
  else if (/(срочн|немедленно|сегодня|прямо сейчас|авари|как можно скорее|горит|затопи|простаива|в течение часа)/i.test(t)) urgency = 'high';

  let city = null;
  for (const [name, re] of MOCK_CITIES) { if (re.test(t)) { city = name; break; } }

  const confidence = best === 'other' ? 0.3 : (bestHits >= 2 ? 0.8 : 0.65);
  const words = t.replace(/\s+/g, ' ').trim().split(' ').filter(Boolean);
  const head = words.slice(0, 14).join(' ') + (words.length > 14 ? '…' : '');
  const summary = (CATEGORY_RU[best] + ': ' + head).trim();
  const needs_human = best === 'complaint' || confidence < 0.6 || (best === 'spam' && confidence < 0.8);
  return {
    category: best,
    urgency,
    city,
    budget_rub: mockParseBudget(t),
    summary,
    next_step: MOCK_NEXT_STEP[best],
    needs_human,
    confidence,
  };
}
