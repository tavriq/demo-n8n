// Модерация публичной доски: короткий стоп-лист грубой лексики. Заявка с таким
// текстом принимается и разбирается, но на доске её текст не показывается.
// Корни берутся с начала слова, чтобы не цеплять «употребляя», «страхуем», «хлебать».
const RUDE_RE = new RegExp('(?<![\\p{L}])(?:' + [
  'ху[йеёияю]', 'пизд', 'еба', 'ебл', 'ёб', 'заеб', 'заёб', 'выеб', 'уеб', 'долбо[её]б', 'бля', 'сук[аиу]',
  'мудак', 'мудил', 'пид[оа]р', 'гандон', 'шлюх', 'мраз', 'ублюд', 'твар[ьи]', 'сдохн', 'дебил',
  'fuck', 'shit', 'bitch', 'cunt',
].join('|') + ')', 'iu');

function isRude(...texts) {
  return texts.some((t) => RUDE_RE.test(String(t == null ? '' : t)));
}

// Почему текст заявки скрыт на доске (null — показывать).
function hiddenReason(r) {
  if (isRude(r.text_masked, r.summary, r.next_step, r.city)) return 'грубая лексика';
  if (r.category === 'spam') return 'похоже на спам';
  if (r.needs_human === true || r.needs_human === 'true' || r.needs_human === 1) return 'ждёт менеджера: жалоба или неясная заявка';
  return null;
}
